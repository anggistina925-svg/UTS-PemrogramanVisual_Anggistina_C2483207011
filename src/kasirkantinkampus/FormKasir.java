    private void btnBayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBayarActionPerformed
    try {String hargaText = txtHarga.getText().trim();
    String jumlahText = txtJumlah.getText().trim();
    String pembayaranText = txtPembayaran.getText().trim();

    if (hargaText.isEmpty() || jumlahText.isEmpty()
            || pembayaranText.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Lengkapi semua data terlebih dahulu!");
        return;
    }

    long harga = Long.parseLong(hargaText);
    int jumlah = Integer.parseInt(jumlahText);
    long pembayaran = Long.parseLong(pembayaranText);

    if (harga < 0 || jumlah <= 0 || pembayaran < 0) {
        JOptionPane.showMessageDialog(this,
                "Data tidak valid!");
        return;
    }

    long total = Math.multiplyExact(harga, jumlah);
    lblTotal.setText("Rp" + String.format("%,d", total));

    if (pembayaran < total) {
        lblKembalian.setText("Rp0");
        JOptionPane.showMessageDialog(this,
                "Pembayaran masih kurang!");
        return;
    }

    long kembalian = pembayaran - total;
    lblKembalian.setText("Rp" + String.format("%,d", kembalian));

    JOptionPane.showMessageDialog(this,
            "Pembayaran berhasil!");

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Masukkan angka yang benar!");
} catch (ArithmeticException e) {
    JOptionPane.showMessageDialog(this,
            "Nilai transaksi terlalu besar!");
} 
    }//GEN-LAST:event_btnBayarActionPerformed

